#include <stdio.h>
#include <stdlib.h>
#include <math.h>

// Функция для прибавления j-й строки, умноженной на α, к i-й строке
void addRowToRow(double **matrix, int n, int m, int i, int j, double alpha)
{
    if (i < 0 || i >= n || j < 0 || j >= n) // Проверка на корректность индексов строк
    {
        printf("Ошибка: неверные индексы строк\n");
        return;
    }
    for (int k = 0; k < m; k++) // Проходим по каждому элементу строки и прибавляем к 
    {                           // нему соответствующий элемент j-й строки, умноженный на α
        matrix[i][k] += alpha * matrix[j][k];
    }
}

// Функция для приведения матрицы к верхнетреугольной форме методом Гаусса
void toUpperTriangular(double **matrix, int n, int m)
{
    for (int col = 0; col < m && col < n; col++) // Проходим по каждому столбцу, но не дальше количества строк
    {
        // Поиск ведущего элемента
        int maxRow = col;
        for (int row = col + 1; row < n; row++) // Проходим по строкам ниже текущей и ищем строку с максимальным 
        {                                       // по абсолютной величине элементом в текущем столбце
            if (fabs(matrix[row][col]) > fabs(matrix[maxRow][col])) // fabs для сравнения по абсолютной величине, 
            {                                                       // так как элемент может быть отрицательным     
                maxRow = row;
            }
        }

        // Обмен строк если необходимо
        if (maxRow != col) // Если строка с максимальным элементом не совпадает с текущей, то меняем их местами
        {
            double *temp = matrix[col]; // Сохраняем указатель на текущую строку
            matrix[col] = matrix[maxRow];   // Меняем указатель на текущую строку на указатель на строку с 
                                            // максимальным элементом
            matrix[maxRow] = temp;  // Меняем указатель на строку с максимальным элементом на сохраненный 
                                    // указатель на текущую строку
        }

        // Прямой ход: обнуление элементов ниже диагонали
        if (fabs(matrix[col][col]) > 1e-10) // Проверяем, что ведущий элемент не слишком мал, чтобы избежать деления на ноль
        {
            for (int row = col + 1; row < n; row++) // Проходим по строкам ниже текущей и обнуляем элементы в текущем столбце
            {
                double alpha = -matrix[row][col] / matrix[col][col]; // Вычисляем коэффициент для обнуления элемента
                addRowToRow(matrix, n, m, row, col, alpha); // Прибавляем к row-й строке col-ю строку, умноженную на α, 
                                                            // что приводит элемент в текущем столбце к нулю
            }
        }
    }
}

// Функция для вывода матрицы
void printMatrix(double **matrix, int n, int m)
{
    for (int i = 0; i < n; i++)
    {
        for (int j = 0; j < m; j++)
        {
            printf("%+5.2lf ", matrix[i][j]); // Выводим элемент с двумя знаками после запятой 
        }
        printf("\n");
    }
    printf("\n");
}

int main()
{
    int n, m;

    printf("Введите количество строк и столбцов матрицы: ");
    scanf("%d%d", &n, &m);

    double **matrix = (double **)malloc(n * sizeof(double *)); // Выделяем память для массива указателей на строки
    for (int i = 0; i < n; i++)
    {
        matrix[i] = (double *)malloc(m * sizeof(double));
    }

    srand(42); // Фиксированное значение для генератора случайных чисел для воспроизводимости
    for (int i = 0; i < n; i++)
    {
        for (int j = 0; j < m; j++)
        {
            matrix[i][j] = (double)(rand() % 100) / 10.0 - 5.0; // Заполняем матрицу случайными числами от -5.0 до 4.9
        }
    }

    printf("\nИсходная матрица:\n");
    printMatrix(matrix, n, m); // Выводим исходную матрицу

    toUpperTriangular(matrix, n, m); // Приводим матрицу к верхнетреугольной форме

    printf("Матрица в верхнетреугольной форме:\n");
    printMatrix(matrix, n, m);  // Выводим результат

    for (int i = 0; i < n; i++) // Освобождаем память, выделенную для матрицы
    {
        free(matrix[i]);
    }
    free(matrix);

    return 0;
}
